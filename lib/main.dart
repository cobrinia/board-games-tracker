import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'core/app_scope.dart';
import 'core/auth/auth_repository.dart';
import 'core/auth/firebase_auth_repository.dart';
import 'core/services/analytics_service.dart';
import 'core/services/crash_reporting.dart';
import 'core/theme/app_theme.dart';
import 'features/auth/auth_gate.dart';
import 'firebase_options.dart';

//import 'package:flutter/rendering.dart'; //файли для дебагу

// Project structure:
//   core/      - theme, reusable widgets, auth repository, Firebase services,
//                mock data, validators, formatters
//   features/  - one folder per app section (auth, home, catalog, sessions,
//                players, settings)

Future<void> main() async {
  //debugPaintSizeEnabled = true;
  WidgetsFlutterBinding.ensureInitialized();

  // firebase_options.dart is generated by `flutterfire configure`.
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Must run before runApp() so that errors during start-up are reported.
  await CrashReporting.init();

  final analytics = AnalyticsService();
  final authRepository = FirebaseAuthRepository(analytics: analytics);

  runApp(MyApp(authRepository: authRepository, analytics: analytics));
}

class MyApp extends StatelessWidget {
  const MyApp({
    super.key,
    required this.authRepository,
    required this.analytics,
  });

  final AuthRepository authRepository;
  final AnalyticsService analytics;

  @override
  Widget build(BuildContext context) {
    return AppScope(
      auth: authRepository,
      analytics: analytics,
      child: MaterialApp(
        title: 'GameShelf',
        debugShowCheckedModeBanner: false,
        theme: AppTheme.light,
        navigatorObservers: [analytics.rootObserver],
        // Shows a splash while the saved session is restored, then either
        // the login screen or the main app.
        home: const AuthGate(),
      ),
    );
  }
}
